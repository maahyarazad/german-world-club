import { randomBytes } from 'node:crypto'
import { PROBLEMS } from '@gwc/contracts/errors'
import type { RedeemerKind, Redemption } from '@gwc/contracts/redemptions'
import { withTransaction } from '../../../db/query.ts'
import { forbidden } from '../../../authz/require-permission.ts'
import { loadMediaItems } from '../../media/application/media-items.ts'
import { VISIBLE_OFFER, OFFER_JOINS } from '../../offers/application/offer.ts'
import type { GwcApp } from '../../../app.ts'

type Queryable = { query: (text: string, values?: unknown[]) => Promise<{ rows: any[] }> }

export type Redeemer = { kind: RedeemerKind; id: string; organisationId?: string }

/**
 * Redeeming an offer (feature 035, research R8).
 *
 * Any active account may redeem — a member, staff, or a merchant or partner
 * user — except a merchant on its own organisation's offers, which would let it
 * inflate its own report. Who the redeemer is comes from the session, never from
 * the request.
 *
 * Exactness is the database's, in one transaction, under a row lock on the
 * offer: the units remaining, the per-person limit and the retry check are all
 * decided while nobody else can change them, so a hundred simultaneous
 * redemptions of the last unit leave exactly one. Nothing is sent, mailed or
 * announced inside it.
 *
 * `requestId` is generated by the client once per tap. A repeat — a double tap,
 * or a retry after a lost response — returns the original redemption and changes
 * nothing, checked both before the lock and again after it, because a second
 * request that was waiting on the lock must find the first's row.
 */

/** A reference a person can read out at the till: unambiguous letters and digits, no I, O, 0 or 1. */
const ALPHABET = '23456789ABCDEFGHJKLMNPQRSTUVWXYZ'
export function newReference(): string {
  const bytes = randomBytes(10)
  let out = ''
  for (const byte of bytes) out += ALPHABET[byte % ALPHABET.length]
  return `GWC-${out.slice(0, 5)}-${out.slice(5)}`
}

const REPLAY_SQL = `
  SELECT r.id, r.reference, r.redeemed_at, r.offer_id
    FROM redemptions r
   WHERE r.redeemer_kind = $1::account_kind AND r.redeemer_id = $2 AND r.request_id = $3`

async function view(db: Queryable, row: { id: unknown; reference: unknown; redeemed_at: unknown; offer_id: unknown }): Promise<Redemption> {
  const { rows } = await db.query(
    `SELECT o.id, o.title, op.display_name,
            (SELECT m.asset_id FROM offer_media m WHERE m.offer_id = o.id ORDER BY m.position LIMIT 1) AS lead_asset_id
       FROM offers o
       LEFT JOIN organisation_profiles op ON op.organisation_id = o.organisation_id
      WHERE o.id = $1`,
    [row.offer_id],
  )
  const offer = rows[0]
  const lead = offer?.lead_asset_id ? (await loadMediaItems(db, [String(offer.lead_asset_id)])).get(String(offer.lead_asset_id)) : null
  const thumb = lead?.variants.find((v) => v.variant === 'thumb')?.url ?? lead?.posterUrl ?? null
  return {
    id: String(row.id),
    reference: String(row.reference),
    redeemedAt: new Date(row.redeemed_at as string).toISOString(),
    offerId: String(row.offer_id),
    offerTitle: String(offer?.title ?? ''),
    merchantName: offer?.display_name ?? null,
    thumbnailUrl: thumb,
  }
}

export async function redeemOffer(
  app: GwcApp,
  { offerId, requestId, redeemer }: { offerId: string; requestId: string; redeemer: Redeemer },
): Promise<{ redemption: Redemption; replay: boolean }> {
  try {
    return await withTransaction(app.pg, async (client) => {
      const replayOf = async () => {
        const { rows } = await client.query(REPLAY_SQL, [redeemer.kind, redeemer.id, requestId])
        if (rows.length === 0) return null
        // The same request id used for a different offer is a client mistake, not a retry.
        if (String(rows[0].offer_id) !== offerId) {
          throw forbidden(PROBLEMS.CONFLICT, 'This request was already used for a different offer.')
        }
        return { redemption: await view(client, rows[0]), replay: true }
      }

      const early = await replayOf()
      if (early) return early

      // The row lock: everything below is decided while nobody else can change
      // the offer. `VISIBLE_OFFER` is re-applied here, so an offer withdrawn, or
      // a store switched off, a moment ago is refused now.
      const { rows } = await client.query(
        `SELECT o.id, o.organisation_id, o.category_id, o.remaining, o.per_person_limit,
                o.regular_price_cents, o.member_price_cents
           FROM offers o
           ${OFFER_JOINS}
          WHERE o.id = $1 AND ${VISIBLE_OFFER}
          FOR UPDATE OF o`,
        [offerId],
      )
      // Indistinguishable from an unknown id: expired, withdrawn, not yet valid,
      // a deactivated store and a nonexistent offer all answer the same way.
      if (rows.length === 0) throw forbidden(PROBLEMS.NOT_FOUND, 'No such offer.')
      const offer = rows[0]

      // A second request that waited on the lock finds the first one's row here.
      const late = await replayOf()
      if (late) return late

      if (redeemer.kind === 'merchant' && redeemer.organisationId === String(offer.organisation_id)) {
        throw forbidden(PROBLEMS.OWN_OFFER, 'An organisation cannot redeem its own offer.')
      }
      if (offer.remaining !== null && offer.remaining <= 0) {
        throw forbidden(PROBLEMS.OFFER_SOLD_OUT, 'No units of this offer remain.')
      }
      if (offer.per_person_limit !== null) {
        const { rows: used } = await client.query(
          `SELECT count(*)::int AS n FROM redemptions
            WHERE offer_id = $1 AND redeemer_kind = $2::account_kind AND redeemer_id = $3`,
          [offerId, redeemer.kind, redeemer.id],
        )
        if (used[0].n >= offer.per_person_limit) {
          throw forbidden(PROBLEMS.PER_PERSON_LIMIT_REACHED, 'You have already redeemed this offer the most times it allows.')
        }
      }

      if (offer.remaining !== null) {
        await client.query('UPDATE offers SET remaining = remaining - 1 WHERE id = $1', [offerId])
      }

      // Only when both prices exist: a freebie has no saving to estimate, and
      // reports must not invent one.
      const saving = offer.regular_price_cents !== null && offer.member_price_cents !== null
        ? offer.regular_price_cents - offer.member_price_cents
        : null

      // `organisation_id` and `category_id` are copied from the offer now, so a
      // later change of category does not rewrite what was reported.
      let inserted: { id: unknown; reference: unknown; redeemed_at: unknown } | undefined
      for (let attempt = 0; attempt < 5 && !inserted; attempt += 1) {
        // A savepoint, so a reference collision retries without aborting the whole transaction.
        await client.query('SAVEPOINT reference')
        try {
          const result = await client.query(
            `INSERT INTO redemptions (offer_id, redeemer_kind, redeemer_id, request_id, organisation_id,
                                      category_id, reference, estimated_saving_cents)
             VALUES ($1, $2::account_kind, $3, $4, $5, $6, $7, $8)
             RETURNING id, reference, redeemed_at`,
            [offerId, redeemer.kind, redeemer.id, requestId, offer.organisation_id, offer.category_id, newReference(), saving],
          )
          inserted = result.rows[0]
          await client.query('RELEASE SAVEPOINT reference')
        } catch (error) {
          await client.query('ROLLBACK TO SAVEPOINT reference')
          const e = error as { code?: string; constraint?: string }
          if (e.code === '23505' && e.constraint === 'redemptions_reference_key') continue
          throw error
        }
      }
      if (!inserted) throw new Error('could not allocate a unique redemption reference')

      return { redemption: await view(client, { ...inserted, offer_id: offerId }), replay: false }
    })
  } catch (error) {
    // The insert trigger refuses an account that no longer exists or is not
    // active (a merchant user whose organisation was suspended after sign-in).
    if ((error as { code?: string }).code === '23503' && /redeemer/.test((error as Error).message)) {
      throw forbidden(PROBLEMS.ACCOUNT_INACTIVE, 'This account cannot redeem offers.')
    }
    throw error
  }
}
